// Generate valibot schemas from the backend OpenAPI so validation rules live in
// one place (the Pydantic models). Covers the write models only (*In/*Patch/BookIn).
// ponytail: hand-rolled emitter for the shapes this API uses (scalars, optional,
// nullable, min bounds). Swap for @hey-api/openapi-ts valibot output if the schema
// grows nested objects / enums / oneOf this doesn't handle.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const schemas = JSON.parse(readFileSync(root + '../backend/openapi.json', 'utf8')).components.schemas;

// resolve a local $ref (e.g. an enum schema Pydantic emits for a StrEnum field)
const deref = (s) => {
	if (s && s.$ref) {
		const name = s.$ref.replace('#/components/schemas/', '');
		return schemas[name] ?? s;
	}
	return s;
};
// unwrap the anyOf: [T, null] that Pydantic emits for `T | None`, deref-ing members
const nullable = (s) => Array.isArray(s.anyOf) && s.anyOf.some((x) => x.type === 'null');
const nonNull = (s) => deref(s.anyOf ? s.anyOf.find((x) => x.type !== 'null') ?? {} : s);

function scalar(s) {
	// build a flat list of pipe steps: base type, then any constraints
	if (Array.isArray(s.enum)) return `v.picklist(${JSON.stringify(s.enum)})`;
	const steps = [
		s.type === 'integer' ? 'v.number(), v.integer()' : s.type === 'number' ? 'v.number()' : s.type === 'boolean' ? 'v.boolean()' : 'v.string()'
	];
	if (s.exclusiveMinimum !== undefined) steps.push(`v.gtValue(${s.exclusiveMinimum}, 'must be greater than ${s.exclusiveMinimum}')`);
	else if (s.minimum !== undefined) steps.push(`v.minValue(${s.minimum})`);
	if (s.maxLength !== undefined) steps.push(`v.maxLength(${s.maxLength})`);
	return steps.length === 1 && !steps[0].includes(',') ? steps[0] : `v.pipe(${steps.join(', ')})`;
}

function field(s) {
	const inner = scalar(nonNull(s));
	return nullable(s) ? `v.nullable(${inner})` : inner;
}

const enums = {}; // FIELD_OPTIONS arrays, deduped by field name across models

function model(name, def) {
	const required = new Set(def.required ?? []);
	const props = Object.entries(def.properties ?? {}).map(([key, s]) => {
		const opts = nonNull(s).enum;
		if (Array.isArray(opts)) enums[`${key.toUpperCase()}_OPTIONS`] = opts;
		const f = field(s);
		return required.has(key) ? `\t\t${key}: ${f},` : `\t\t${key}: v.optional(${f}),`;
	});
	return `export const ${name} = v.object({\n${props.join('\n')}\n\t});`.replace(/\n\t\t/g, '\n\t');
}

const names = Object.keys(schemas).filter((n) => /(?:In|Patch)$/.test(n) || n === 'BookIn');
const models = names.map((n) => model(n, schemas[n])); // populates `enums` as a side effect
const enumExports = Object.entries(enums).map(([k, vals]) => `export const ${k} = ${JSON.stringify(vals)} as const;`);
const out = [
	'// GENERATED by scripts/gen-validators.mjs from backend/openapi.json. Do not edit.',
	"import * as v from 'valibot';",
	'',
	...enumExports,
	...(enumExports.length ? [''] : []),
	...models,
	''
].join('\n');

writeFileSync(root + 'src/lib/validators.ts', out);
console.log(`wrote src/lib/validators.ts (${names.length} schemas)`);
